class PixelFont:
    def __init__(self, scale: int = 2) -> None:
        self.scale = scale

    def render(self, text: str, _antialias: bool, color: tuple[int, int, int]):
        import pygame

        normalized = text.upper()
        width = sum((len(GLYPHS.get(char, GLYPHS[" "])[0]) + 1) for char in normalized)
        surface = pygame.Surface((max(1, width * self.scale), 7 * self.scale), pygame.SRCALPHA)
        cursor_x = 0
        for char in normalized:
            glyph = GLYPHS.get(char, GLYPHS[" "])
            for y, row in enumerate(glyph):
                for x, pixel in enumerate(row):
                    if pixel == "1":
                        pygame.draw.rect(
                            surface,
                            color,
                            (
                                (cursor_x + x) * self.scale,
                                y * self.scale,
                                self.scale,
                                self.scale,
                            ),
                        )
            cursor_x += len(glyph[0]) + 1
        return surface
